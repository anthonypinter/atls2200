// Builds search-index.js (window.SEARCH_INDEX) from the lesson pages and the glossary, for js/search.js.
// It's a script rather than JSON so search also works when the book is opened straight from the file system.
// Each lesson is split into sections at the same headings js/chrome.js lists under "On this page" (.section-title h2
// and the notes panels), with the same generated ids, so a result can link straight to its section.
import { readFileSync } from "node:fs";
import { join } from "node:path";

const ENTITIES = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", rarr: "→", larr: "←", hellip: "…", mdash: "—", ndash: "–", times: "×" };
const decode = (s) => s.replace(/&(#x?[0-9a-f]+|[a-z]+);/gi, (m, e) =>
  e[0] === "#" ? String.fromCodePoint(e[1].toLowerCase() === "x" ? parseInt(e.slice(2), 16) : +e.slice(1)) : ENTITIES[e.toLowerCase()] ?? m);
// Inline tags vanish without a gap ("<em>container</em>," → "container,"); other tags become spaces.
const INLINE = /<\/?(a|abbr|b|code|em|i|kbd|mark|q|s|small|span|strong|sub|sup|u|var)\b[^>]*>/gi;
const text = (html) => decode(html.replace(INLINE, "").replace(/<[^>]+>/g, " ")).replace(/\s+/g, " ").trim();

// Must match sectionsOf() in js/chrome.js.
const sectionId = (heading, used) => {
  const base = "sec-" + (heading.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "section");
  let id = base, n = 2;
  while (used.has(id)) id = `${base}-${n++}`;
  used.add(id);
  return id;
};

export function buildSearchIndex(root, book, glossary, glossaryId) {
  const lessons = [];
  book.parts.forEach((part, p) => part.lessons.forEach((l, i) => {
    let html = readFileSync(join(root, l.slug + ".html"), "utf8");
    html = html.slice(html.indexOf("<body"));
    const main = html
      .replace(/<(script|style|textarea)\b[\s\S]*?<\/\1>/gi, "")
      .replace(/<!--[\s\S]*?-->/g, "")
      .replace(/<nav class="crumbs"[\s\S]*?<\/nav>|<footer[\s\S]*?<\/footer>/g, "");
    const notesAt = main.indexOf('<section class="notes"');
    const used = new Set([...main.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]));
    const heads = [...main.matchAll(/<h2([^>]*)>([\s\S]*?)<\/h2>/g)].filter((m) =>
      /class="section-title"[^]*$/.test(main.slice(Math.max(0, m.index - 200), m.index)) || (notesAt >= 0 && m.index > notesAt));
    const sections = [];
    heads.forEach((m, k) => {
      const end = k + 1 < heads.length ? heads[k + 1].index : main.length;
      const title = text(m[2]);
      const own = /\sid="([^"]+)"/.exec(m[1]);
      sections.push({ id: own ? own[1] : sectionId(title, used), title, text: text(main.slice(m.index + m[0].length, end)) });
    });
    // intro is the lede under the title (used for snippets); more is everything else before the first section,
    // mostly playground labels and options, which is worth matching but not worth showing.
    const head = /<header class="page-head">([\s\S]*?)<\/header>/.exec(main);
    const lede = head && /<p class="lede">([\s\S]*?)<\/p>/.exec(head[1]);
    const intro = lede ? text(lede[1]) : "";
    const more = text(main.slice(head ? head.index + head[0].length : 0, heads.length ? heads[0].index : main.length));
    lessons.push({ slug: l.slug, num: `${p + 1}.${i + 1}`, title: l.title, desc: l.desc, props: l.props, intro, more, sections });
  }));
  const terms = glossary.map(([term, cat, def, ex, page]) => ({ term, id: glossaryId(term), cat, def, ex: ex || "", page: page || "" }));
  return `/* Generated by scripts/check.mjs --write from the lesson pages and glossary-terms.js. Don't edit by hand. */\nwindow.SEARCH_INDEX = ${JSON.stringify({ lessons, terms })};\n`;
}
